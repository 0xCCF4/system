#!/usr/bin/env python3
"""Generate the shell completions of box, box-pi and box-claude.

    python3 completions.py <share-dir>

Writes <share-dir>/bash-completion/completions/box, <share-dir>/zsh/site-functions/_box
and <share-dir>/fish/vendor_completions.d/box.fish. The three names share each file.
The bash and fish files define all of them. The zsh file names them in its #compdef
line. default.nix adds the symlinks that the shells look for.

The options come from box.interface(prog), which reads the argparse parser of that
command name. So the completions show exactly the flags the parser accepts, with the
help text and the argument kind that the parser holds.
"""

from __future__ import annotations

import sys
from pathlib import Path

import box

COMMANDS = ("box", "box-pi", "box-claude")
HEADER = "Generated by pkgs/box/completions.py from the parser in box.py. Do not edit."


def is_help(option: box.Option) -> bool:
    return "-h" in option.strings


def names(option: box.Option) -> str:
    """The option strings of a flag, space separated, as the shells spell them."""
    return " ".join(option.strings)


def words(command: str) -> str:
    """Every option string of a command name, for the one-word completion of bash."""
    return " ".join(name for option in box.interface(command) for name in option.strings)


def flags_with(command: str, kind: str) -> list[str]:
    """The option strings of a command name whose argument is of this kind."""
    return [
        name for option in box.interface(command) if option.complete == kind for name in option.strings
    ]


def bash(share: Path) -> str:
    cases = "\n".join(f'    {command}) options="{words(command)}" ;;' for command in COMMANDS)
    path_flags = " | ".join(sorted({name for c in COMMANDS for name in flags_with(c, "path")}))
    env_flags = " | ".join(sorted({name for c in COMMANDS for name in flags_with(c, "env")}))
    return f"""# Bash completion for box, box-pi and box-claude.
# {HEADER}
_box() {{
  local cur prev cmd options
  cur="${{COMP_WORDS[COMP_CWORD]}}"
  prev="${{COMP_WORDS[COMP_CWORD - 1]}}"
  cmd="${{COMP_WORDS[0]##*/}}"

  case "$prev" in
    {path_flags})
      mapfile -t COMPREPLY < <(compgen -f -- "$cur")
      return
      ;;
    {env_flags})
      mapfile -t COMPREPLY < <(compgen -v -- "$cur")
      return
      ;;
  esac

  case "$cmd" in
{cases}
    *) return ;;
  esac

  if [[ "$cur" == -* ]]; then
    mapfile -t COMPREPLY < <(compgen -W "$options" -- "$cur")
  elif [[ "$cmd" == box ]]; then
    # the generic launcher runs any command
    mapfile -t COMPREPLY < <(compgen -c -- "$cur")
  fi
}}

complete -F _box box box-pi box-claude
"""


def zsh_spec(option: box.Option) -> str:
    """One _arguments spec of a flag, from what the parser knows about it."""
    text = option.help.replace("'", "")
    if is_help(option):
        return f"'(-h --help)'{{-h,--help}}'[{text}]'"
    name = option.strings[0]
    if not option.takes_value:
        return f"'{name}[{text}]'"
    kind = {
        "path": "path:_files",
        "env": "variable:_parameters",
    }.get(option.complete, f"{option.metavar.lower() or 'value'}:")
    return f"'{name}[{text}]:{kind}'"


def zsh_specs(command: str) -> str:
    """Every spec of one command name, plus the command completion of the generic launcher."""
    specs = [zsh_spec(option) for option in box.interface(command)]
    if command == "box":
        specs.append("'*::command:_command_names -e'")
    return " ".join(specs)


def zsh(share: Path) -> str:
    cases = "\n".join(
        f"    {command}) specs=({zsh_specs(command)}) ;;" for command in COMMANDS
    )
    return f"""#compdef box box-pi box-claude
# Zsh completion for box, box-pi and box-claude.
# {HEADER}

_box() {{
  local -a specs
  case "$service" in
{cases}
    *) return 1 ;;
  esac
  _arguments -s "${{specs[@]}}"
}}

compdef _box box box-pi box-claude
"""


def fish_escape(text: str) -> str:
    return text.replace("'", "\\'")


def fish_line(command: str, option: box.Option) -> str:
    parts = [f"complete -c {command}"]
    for name in option.strings:
        if name.startswith("--"):
            parts.append(f"--long-option {name[2:]}")
        else:
            parts.append(f"--short-option {name[1:]}")
    if option.takes_value:
        parts.append("--require-parameter")
        if option.complete == "path":
            parts.append("--force-files")
    parts.append(f"--description '{fish_escape(option.help)}'")
    return " ".join(parts)


def fish(share: Path) -> str:
    lines = ["# Fish completion for box, box-pi and box-claude.", f"# {HEADER}", ""]
    for command in COMMANDS:
        lines += [fish_line(command, option) for option in box.interface(command)]
        lines.append("")
    lines.append("# The generic launcher runs any command after its options.")
    lines.append("complete -c box --no-files --arguments '(__fish_complete_command)'")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        print("usage: completions.py <share-dir>", file=sys.stderr)
        return 2
    share = Path(args[0])
    files = {
        "bash-completion/completions/box": bash(share),
        "zsh/site-functions/_box": zsh(share),
        "fish/vendor_completions.d/box.fish": fish(share),
    }
    for name, text in files.items():
        target = share / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
